#!/usr/bin/env python3
"""Freeze PyRadiomics 3.1.0 original-image features on D4 brain1.

Quote (PyRadiomics 3.1.0 customisation / default extractor):
- binWidth = 25
- interpolator = sitkBSpline
- label = 1
- image type Original only (no LoG/wavelet)
- no resampledPixelSpacing (native voxel grid)
- voxelArrayShift = 0

Install that exact tag, then run this script once. Do not edit the CSV by hand.

    pip install 'git+https://github.com/AIM-Harvard/pyradiomics.git@v3.1.0'
    python3 scripts/freeze_pyradiomics_brain1.py
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMAGE = ROOT / "data" / "pyradiomics" / "brain1" / "brain1_image.nrrd"
MASK = ROOT / "data" / "pyradiomics" / "brain1" / "brain1_label.nrrd"
OUT = ROOT / "tests" / "references" / "pyradiomics_3.1.0_brain1.csv"


def main() -> None:
    from radiomics import __version__, featureextractor  # noqa: PLC0415

    if not IMAGE.exists() or not MASK.exists():
        raise SystemExit(f"D4 brain1 missing: {IMAGE} / {MASK}")

    extractor = featureextractor.RadiomicsFeatureExtractor()
    result = extractor.execute(str(IMAGE), str(MASK))
    rows = []
    for key, value in result.items():
        if not str(key).startswith("original_"):
            continue
        try:
            rows.append((str(key), float(value)))
        except (TypeError, ValueError):
            continue
    rows.sort()
    if not rows:
        raise SystemExit("no original_* numeric features in PyRadiomics output")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as fh:
        fh.write("# Frozen PyRadiomics 3.1.0 brain1 original-image features.\n")
        fh.write("# Source: AIM-Harvard/pyradiomics tag v3.1.0,\n")
        fh.write("# default RadiomicsFeatureExtractor, Original image type, brain1_image/label.nrrd.\n")
        fh.write("# Do not edit by hand. Regenerated by scripts/freeze_pyradiomics_brain1.py.\n")
        fh.write(f"# pyradiomics_version={__version__}\n")
        writer = csv.writer(fh)
        writer.writerow(["radix_key", "value"])
        writer.writerows(rows)
    print(f"wrote {len(rows)} rows to {OUT} (pyradiomics {__version__})")


if __name__ == "__main__":
    main()
